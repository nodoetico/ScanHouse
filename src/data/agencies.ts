function makeAnalytics(
  visitors: number,
  visitorsToLeads: number,
  visitorsToRequests: number,
  visitorsToConfirmed: number,
  visitorsToOpps: number,
  envScenes: { scene: string; time: string; count: number }[],
  comp: { propertyId: string; visitors: number; aiQuestions: number; leads: number; visits: number }[],
): AnalyticsData {
  const funnel = makeFunnel(visitors, visitorsToLeads, visitorsToRequests, visitorsToConfirmed, visitorsToOpps);
  return {
    visitors,
    uniqueVisitors: Math.round(visitors * 0.79),
    avgTime: '4m 32s',
    toursCompleted: Math.round(visitors * 0.3),
    interactions: visitors * 2,
    leads: visitorsToLeads,
    visitRequests: visitorsToRequests,
    whatsappContacts: Math.round(visitorsToLeads * 0.7),
    aiConversations: Math.round(visitors * 0.08),
    visitorsByDay: makeVisitorsSeries(visitors),
    interactionsByDay: makeInteractionsSeries(visitors * 2),
    environmentVisits: envScenes.map(({ scene, time }) => ({ scene, time })),
    propertyComparison: comp,
    funnel: funnel.funnel,
    conversions: funnel.conversions,
  };
}

