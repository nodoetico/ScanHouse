function makeFunnel(visitors: number, leads: number, requested: number, confirmed: number, opportunities: number) {
  const pct = (a: number, b: number) => ((a / b) * 100).toFixed(1).replace('.', ',');
  return {
    funnel: [
      { label: 'Visitantes', value: visitors },
      { label: 'Leads', value: leads },
      { label: 'Visitas solicitadas', value: requested },
      { label: 'Visitas confirmadas', value: confirmed },
      { label: 'Oportunidades', value: opportunities },
    ],
    conversions: [
      { label: 'Visitante → Lead', value: `${pct(leads, visitors)}%` },
      { label: 'Lead → Visita', value: `${pct(requested, leads)}%` },
      { label: 'Visita → Confirmada', value: `${pct(confirmed, requested)}%` },
      { label: 'Confirmada → Oportunidad', value: `${pct(opportunities, confirmed)}%` },
    ],
  };
}

function makeVisitorsSeries(total: number): { day: string; count: number }[] {
  const seed = total / 30;
  return Array.from({ length: 30 }, (_, i) => {
    const day = new Date(2026, 8, 10 - i).toLocaleDateString('es-AR', { day: '2-digit', month: 'short' });
    const wave = Math.round((Math.sin(i * 0.7) + 1.2) * seed * 0.35 + seed * 0.55 + (i % 5) * 6);
    return { day, count: wave };
  }).reverse();
}

function makeInteractionsSeries(total: number): { day: string; count: number }[] {
  const series = makeVisitorsSeries(Math.round(total / 2.3));
  return series.map(s => ({ ...s, count: Math.round(s.count * 2.3) }));
}

