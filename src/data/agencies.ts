function makeLeads(
  rows: [string, string, string, string, Lead['status'], string, Lead['origin'], string, [string, string][]][],
  advisorFallback: string,
  indexOffset = 0,
): Lead[] {
  return rows.map(([id, name, email, phone, status, propertyId, origin, advisor, interactions], i) => ({
    id,
    name,
    email,
    phone,
    propertyId,
    status,
    date: `2026-09-${String(8 - ((i + indexOffset) % 9)).padStart(2, '0')}`,
    origin,
    advisor: advisor || advisorFallback,
    interactions: interactions.map(([time, description]) => ({ time, description })),
  }));
}

